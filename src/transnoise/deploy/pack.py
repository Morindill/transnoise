"""Pack weights.npz into what the C++ code uses (numpy only, runs in the main environment):
  uv run python -m transnoise.deploy.pack data/deploy/<name>/weights.npz [--out-dir cpp/gen]

Output:
  weights.bin   the weights loaded by C++ (float32, with a name table and the model constants; C++ checks every constant on load and refuses on a mismatch)
  config.h      model constants (constexpr). Every shape in C++ comes from here and is fixed at compile time; changing the architecture means regenerating and recompiling

Folding done while packing (mathematically equivalent, only 1e-7-level rounding differences):
  - the gamma and beta of each LayerNorm that feeds a linear layer are folded into that layer: (x_hat*gamma+beta)*W+b = x_hat*(diag(gamma)*W) + (beta*W+b), so LN in C++ only normalizes
  - the final norm_out is folded into the ERB gain head and the deep-filter head likewise
  - the LayerNorm inside the convolution module (between the depthwise convolution and Swish) is not foldable and keeps its gamma and beta
Matrices keep Keras's [input, output] row-major layout, used as is by C++'s loops vectorized over the output dimension.
"""

import argparse
import json
import struct
from pathlib import Path

import numpy as np

MAGIC = b"TNWEIGHT"
ALIGN = 64
# Order of the constant table: CONSTS in config.h and the weights.bin header use the same order; C++ compares them item by item on load
CONST_KEYS = ["sr", "fft", "hop", "nb_erb", "nb_df", "d_model", "n_layers", "n_heads", "ff_mult", "conv_kernel", "window", "lookahead", "df_order"]


def fold(gamma, beta, w, b):
    g, be, w, b = (np.asarray(a, np.float64) for a in (gamma, beta, w, b))
    return (g[:, None] * w).astype(np.float32), (be @ w + b).astype(np.float32)


def tensors(z) -> tuple[dict, list[tuple[str, np.ndarray]]]:
    info = json.loads(str(z["meta"]))
    c = info["config"]
    eps = {float(z[k]) for k in z.files if k.endswith(".eps")}
    assert len(eps) == 1, f"LayerNorm eps values differ: {eps}"  # LN_EPS is a single constant in C++
    out: list[tuple[str, np.ndarray]] = []

    def add(name, a):
        out.append((name, np.ascontiguousarray(a, np.float32)))

    for n in ("erb_in", "spec_in", "mix"):
        add(f"{n}.w", z[f"{n}.kernel"]), add(f"{n}.b", z[f"{n}.bias"])
    for i in range(c["n_layers"]):
        p = f"blocks.{i}"

        def folded(ln, src, dst):  # a linear layer preceded by a LayerNorm
            w, b = fold(z[f"{p}.{ln}.gamma"], z[f"{p}.{ln}.beta"], z[f"{p}.{src}.kernel"], z[f"{p}.{src}.bias"])
            add(f"b{i}.{dst}.w", w), add(f"b{i}.{dst}.b", b)

        def plain(src, dst):
            add(f"b{i}.{dst}.w", z[f"{p}.{src}.kernel"]), add(f"b{i}.{dst}.b", z[f"{p}.{src}.bias"])

        folded("ln_ffa", "ffa1", "ffa1"), plain("ffa2", "ffa2")
        folded("ln_att", "attn.qkv", "qkv")
        add(f"b{i}.rel", z[f"{p}.attn.rel_bias"])
        plain("attn.out", "out")
        folded("ln_conv", "pw1", "pw1")
        plain("dw", "dw")  # [conv_kernel, d_model] taps and [d_model] bias; the LayerNorm after it sits before a nonlinearity and cannot be folded
        add(f"b{i}.dwln.g", z[f"{p}.dw_ln.gamma"]), add(f"b{i}.dwln.b", z[f"{p}.dw_ln.beta"])
        plain("pw2", "pw2")
        folded("ln_ffb", "ffb1", "ffb1"), plain("ffb2", "ffb2")
    for n in ("gain", "df"):
        w, b = fold(z["norm_out.gamma"], z["norm_out.beta"], z[f"{n}.kernel"], z[f"{n}.bias"])
        add(f"{n}.w", w), add(f"{n}.b", b)
    return {"eps": eps.pop(), "info": info}, out


def write_bin(path: Path, consts: list[int], items: list[tuple[str, np.ndarray]]) -> None:
    offs, pos = [], 0
    for _, a in items:
        offs.append(pos)
        pos += a.size
    head = MAGIC + struct.pack("<II", len(consts), len(items)) + struct.pack(f"<{len(consts)}i", *consts)
    for (name, a), o in zip(items, offs):
        assert len(name) < 40, name
        head += name.encode().ljust(40, b"\0") + struct.pack("<QQ", o, a.size)
    head += b"\0" * (-len(head) % ALIGN)
    path.write_bytes(head + b"".join(a.tobytes() for _, a in items))


def write_config(path: Path, c: dict, widths: list[int], eps: float, step: int) -> None:
    assert c["fft"] == 2 * c["hop"], "the C++ implementation assumes fft == 2*hop"
    assert c["d_model"] % c["n_heads"] == 0 and sum(widths) == c["fft"] // 2 + 1
    consts = ", ".join(str(c[k]) for k in CONST_KEYS)
    path.write_text(f"""// Generated by transnoise.deploy.pack; do not edit by hand. All model shapes are compile-time constants; the weights.bin header carries the same constants and they are checked item by item on load.
// Source: checkpoint step {step}
#pragma once
#include <cstdint>

namespace tn {{
inline constexpr int SR = {c['sr']}, FFT = {c['fft']}, HOP = {c['hop']}, BINS = FFT / 2 + 1;
inline constexpr int NB_ERB = {c['nb_erb']}, NB_DF = {c['nb_df']}, ORDER = {c['df_order']};
inline constexpr int D = {c['d_model']}, LAYERS = {c['n_layers']}, HEADS = {c['n_heads']}, DH = D / HEADS, FF = D * {c['ff_mult']}, CK = {c['conv_kernel']};
inline constexpr int WINDOW = {c['window']}, LA = {c['lookahead']};
inline constexpr float ERB_DB_OFFSET = {c['erb_db_offset']!r}f, ERB_DB_SCALE = {c['erb_db_scale']!r}f, LN_EPS = {eps!r}f;
inline constexpr int ERB_WIDTHS[NB_ERB] = {{{', '.join(map(str, widths))}}};
inline constexpr int32_t CONSTS[] = {{{consts}}};  // order:{' '.join(CONST_KEYS)}
}}  // namespace tn
""")


def main() -> None:
    p = argparse.ArgumentParser()
    p.add_argument("npz", type=Path)
    p.add_argument("--out-dir", type=Path, default=None, help="default: next to the npz")
    a = p.parse_args()
    out_dir = a.out_dir or a.npz.parent
    out_dir.mkdir(parents=True, exist_ok=True)
    z = np.load(a.npz)
    extra, items = tensors(z)
    info = extra["info"]
    c = info["config"]
    write_bin(out_dir / "weights.bin", [c[k] for k in CONST_KEYS], items)
    write_config(out_dir / "config.h", c, info["erb_widths"], extra["eps"], info["step"])
    n = sum(a.size for _, a in items)
    print(f"{out_dir}/weights.bin: {len(items)} tensors, {n:,} floats ({n * 4 / 2**20:.2f} MiB); config.h generated (d={c['d_model']}, lookahead={c['lookahead']})")


if __name__ == "__main__":
    main()
